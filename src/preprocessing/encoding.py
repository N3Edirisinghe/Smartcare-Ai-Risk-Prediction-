from sklearn.preprocessing import OneHotEncoder


def create_encoder():
    """
    Create One-Hot Encoder for categorical features.

    handle_unknown='ignore' prevents errors when
    unseen categories appear in test/new data.
    """

    encoder = OneHotEncoder(
        handle_unknown="ignore",
        sparse_output=False
    )

    return encoder


def get_encoded_feature_names(
    encoder,
    categorical_features
):
    """
    Return feature names generated by OneHotEncoder.
    """

    return encoder.get_feature_names_out(
        categorical_features
    )